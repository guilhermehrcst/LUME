#!/usr/bin/env python3
"""E1-A tables: how much of the P5 / P6 / P7 differences is explained by
allocation, first touch and page faults. Pure standard library; reads the raw
and plans CSVs of one results directory, writes derived/e1a_tables.md.

usage: e1a_tables.py <results-dir>
Medians are pooled over all replicates and repetitions of the cell.
"""
import collections
import csv
import glob
import os
import statistics as st
import sys

REG = ["glibc_default", "glibc_default_fresh", "glibc_t1", "glibc_t2", "arena_cold", "arena_warm"]
PROGRAMS = ["final_left", "chain3", "inter_out"]


def main():
    d = sys.argv[1]
    raw, plans = [], []
    for f in sorted(glob.glob(os.path.join(d, "raw_*.csv"))):
        raw += list(csv.DictReader(open(f, newline="")))
    for f in sorted(glob.glob(os.path.join(d, "plans_*.csv"))):
        plans += list(csv.DictReader(open(f, newline="")))
    t = collections.defaultdict(list)
    fl = collections.defaultdict(list)
    sysns = collections.defaultdict(list)
    for r in raw:
        k = (r["program"], int(r["n"]), r["regime"], r["plan"])
        t[k].append(float(r["ns_per_call"]))
        fl[k].append(float(r["minflt_per_call"]))
        sysns[k].append(float(r["stime_ns_per_call"]))
    payload = {}
    for r in plans:
        payload[(r["program"], int(r["n"]), r["plan"])] = float(r["payload_bytes_per_element"])
    med = {k: st.median(v) for k, v in t.items()}
    fmed = {k: st.median(v) for k, v in fl.items()}
    regimes = [x for x in REG if any(k[2] == x for k in med)]
    L = ["# E1-A tables (generated by e1a_tables.py)\n",
         "All values are medians pooled over replicates and repetitions. `a/b` columns are ratios of medians.\n"]
    for program in PROGRAMS:
        sizes = sorted({k[1] for k in med if k[0] == program})
        plan_labels = [p for p in ("P5", "P6", "P7") if (program, sizes[0], regimes[0], p) in med]
        L.append(f"## {program}: plan ratios by regime\n")
        L.append("Ratios > 1 mean the first plan is slower. P5 = materialize, P6 = + reuse, P7 = + fusion (fixed policy).\n")
        hdr = "| N | regime | " + " | ".join(plan_labels) + " (ns) | " + " | ".join(
            f"{a}/{b}" for a, b in [("P5", "P6"), ("P6", "P7"), ("P5", "P7")] if a in plan_labels and b in plan_labels) + " |"
        L.append(hdr)
        L.append("| ---: | --- | " + " | ".join("---:" for _ in plan_labels) + " | " + " | ".join(
            "---:" for a, b in [("P5", "P6"), ("P6", "P7"), ("P5", "P7")] if a in plan_labels and b in plan_labels) + " |")
        for n in sizes:
            for rg in regimes:
                if (program, n, rg, plan_labels[0]) not in med:
                    continue
                vals = {p: med[(program, n, rg, p)] for p in plan_labels}
                rat = [f"{vals[a] / vals[b]:.3f}" for a, b in [("P5", "P6"), ("P6", "P7"), ("P5", "P7")]
                       if a in plan_labels and b in plan_labels]
                L.append(f"| {n} | {rg} | " + " | ".join(f"{vals[p]:.0f}" for p in plan_labels) + " | " + " | ".join(rat) + " |")
        L.append("")
    # allocation/page effect: arena_warm vs the other regimes, per plan
    for program in ("final_left", "chain3"):
        sizes = sorted({k[1] for k in med if k[0] == program})
        L.append(f"## {program}: time under each regime relative to arena_warm (no allocator calls, no page faults)\n")
        labels = [p for p in ("P5", "P6", "P7") if (program, sizes[0], "arena_warm", p) in med]
        others = [r for r in regimes if r != "arena_warm"]
        L.append("| N | plan | " + " | ".join(f"{r}/arena_warm" for r in others) + " |")
        L.append("| ---: | --- | " + " | ".join("---:" for _ in others) + " |")
        for n in sizes:
            for p in labels:
                base = med.get((program, n, "arena_warm", p))
                if base is None:
                    continue
                cells = [f"{med[(program, n, r, p)] / base:.2f}" if (program, n, r, p) in med else "" for r in others]
                L.append(f"| {n} | {p} | " + " | ".join(cells) + " |")
        L.append("")
    # first-touch cost per page: arena_cold - arena_warm over the extra faults
    L.append("## First-touch cost per page fault (arena_cold minus arena_warm, divided by the extra faults)\n")
    L.append("| program | N | plan | extra faults/call | extra ns/call | ns per fault |\n| --- | ---: | --- | ---: | ---: | ---: |")
    for program in ("final_left", "chain3"):
        for n in (65536, 1048576, 4194304, 16777216):
            for p in ("P5", "P6", "P7"):
                kc, kw = (program, n, "arena_cold", p), (program, n, "arena_warm", p)
                if kc in med and kw in med and fmed[kc] > fmed[kw]:
                    extra_f = fmed[kc] - fmed[kw]
                    extra_t = med[kc] - med[kw]
                    L.append(f"| {program} | {n} | {p} | {extra_f:.0f} | {extra_t:.0f} | {extra_t / extra_f:.0f} |")
    L.append("")
    # effective logical bandwidth, warm arena
    L.append("## Effective logical bandwidth in arena_warm (CALCULATED payload model / MEASURED time)\n")
    L.append("Payload per element: add loop 12 B, fused pair loop 16 B, output copy 8 B (a model, not DRAM traffic).\n")
    L.append("| program | N | P5 GB/s | P6 GB/s | P7 GB/s |\n| --- | ---: | ---: | ---: | ---: |")
    for program in ("final_left", "chain3"):
        for n in sorted({k[1] for k in med if k[0] == program}):
            cells = []
            for p in ("P5", "P6", "P7"):
                k = (program, n, "arena_warm", p)
                cells.append(f"{payload[(program, n, p)] * n / med[k]:.1f}" if k in med else "")
            L.append(f"| {program} | {n} | " + " | ".join(cells) + " |")
    L.append("")
    # which regime-dependent quantities exist: system time share of the fault regimes
    L.append("## Share of system (kernel) time in the faulting regimes (final_left, P7)\n")
    L.append("| N | regime | faults/call | sys ns/call (coarse) | wall ns/call |\n| ---: | --- | ---: | ---: | ---: |")
    for n in (1048576, 4194304, 16777216):
        for rg in regimes:
            k = ("final_left", n, rg, "P7")
            if k in med and fmed[k] > 0:
                L.append(f"| {n} | {rg} | {fmed[k]:.0f} | {st.median(sysns[k]):.0f} | {med[k]:.0f} |")
    L.append("")
    # POST HOC, descriptive (not part of the preregistered gates): what a wrong
    # fixed policy would cost. Regret of ALWAYS_MATERIALIZE (P5) and
    # ALWAYS_REUSE (P6, no fusion) against the empirical best distinct plan.
    L.append("## Post hoc: regret of alternative fixed policies (decision cells)\n")
    L.append("Not a preregistered statistic. Regret = median(policy's plan) / median(empirical best plan). "
             "The preregistered fixed policy (P7) is in the gates, not here.\n")
    cell_best = {}
    for (program, n, rg, plan), v in med.items():
        if plan == "FIXED_TWIN":
            continue
        key = (program, n, rg)
        cell_best.setdefault(key, {})[plan] = v
    for pol, label in (("P5", "ALWAYS_MATERIALIZE (P5)"), ("P6", "ALWAYS_REUSE, no fusion (P6)")):
        L.append(f"### {label}\n")
        L.append("| regime | decision cells | median regret | p95 regret | max regret | share > 1.05 | share > 1.15 |\n| --- | ---: | ---: | ---: | ---: | ---: | ---: |")
        for rg in regimes:
            regs = []
            for (program, n, r), plansd in cell_best.items():
                if r != rg or len(plansd) < 2 or pol not in plansd:
                    continue
                regs.append(plansd[pol] / min(plansd.values()))
            if not regs:
                continue
            srt = sorted(regs)
            p95 = srt[max(0, -(-95 * len(srt) // 100) - 1)]
            L.append(f"| {rg} | {len(regs)} | {st.median(regs):.3f} | {p95:.3f} | {max(regs):.3f} | "
                     f"{sum(1 for x in regs if x > 1.05) / len(regs):.2f} | {sum(1 for x in regs if x > 1.15) / len(regs):.2f} |")
        L.append("")
    # Cells in which the fixed plan is not the empirical best (list, whatever the margin).
    L.append("## Cells in which the fixed plan (P7 or its group) is not the lowest-median plan\n")
    L.append("| program | N | regime | fixed ns | best plan | best ns | regret |\n| --- | ---: | --- | ---: | --- | ---: | ---: |")
    fixed_of = {}
    for r in plans:
        if r["is_fixed"] == "1":
            fixed_of[(r["program"], int(r["n"]))] = r["plan"]
    rows = []
    for (program, n, rg), plansd in cell_best.items():
        if len(plansd) < 2:
            continue
        fx = fixed_of[(program, n)]
        best = min(plansd, key=plansd.get)
        if best != fx:
            rows.append((plansd[fx] / plansd[best], program, n, rg, plansd[fx], best, plansd[best]))
    for reg, program, n, rg, fx_ns, best, b_ns in sorted(rows, reverse=True):
        L.append(f"| {program} | {n} | {rg} | {fx_ns:.0f} | {best} | {b_ns:.0f} | {reg:.4f} |")
    if not rows:
        L.append("| (none) | | | | | | |")
    L.append("")
    os.makedirs(os.path.join(d, "derived"), exist_ok=True)
    with open(os.path.join(d, "derived", "e1a_tables.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
